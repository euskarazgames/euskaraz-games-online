import assert from "node:assert/strict";
import {chromium} from "playwright";
const host=process.env.MUNDU_TEST_ORIGIN||"http://127.0.0.1:8787";
const home=await fetch(host+"/");
assert.equal(home.status,200);
const html=await home.text();
assert(html.includes("EUSKARAZ GAMES")&&html.includes("MUNDU")&&html.includes("BASOA"));
assert(!html.includes('class="symbol"'),"The orange square logo must be gone");
assert(html.includes('src="/eg-erronkak.js"'),"Basque quest script missing");
const old=await fetch(host+"/klasiko/?joko=pilota");
assert.equal(old.status,200);
const legacy=await old.text();
assert(legacy.includes("klasiko/bridge.js"),"Classic deep-link script missing");
assert(legacy.length>2500000,"Classic version missing embedded game code");
const b=await fetch(host+"/klasiko/bridge.js");assert.equal(b.status,200);
const browser=await chromium.launch({headless:true,args:["--enable-webgl","--use-gl=angle","--use-angle=swiftshader","--ignore-gpu-blocklist"]});
const page=await browser.newPage({viewport:{width:1440,height:900}});
const errors=[];
page.on("pageerror",err=>errors.push(String(err.message||err)));
await page.goto(host+"/",{waitUntil:"domcontentloaded",timeout:20000});
await page.locator(".gamecard").first().waitFor({timeout:12000});
assert.equal(await page.locator(".gamecard").count(),31,"31 new game cards should render");
assert.equal(await page.locator(".feature-tile").count(),5,"3 sports + 2 Basoa");
await page.locator("#search").fill("azeria");
assert.equal(await page.locator(".gamecard").count(),1,"Search should match Euskara title");
await page.locator("#search").fill("");
await page.locator(".poster .star").first().click();
assert.equal(await page.locator(".poster .star.on").count(),1,"Favoriting should work");
await page.locator("#lang").click();
assert.equal(await page.locator("#search").getAttribute("placeholder"),"Buscar juego...","Spanish UI toggle");
await page.locator("#lang").click();
await page.locator("#heroPlay").click();
await page.locator("#eg-extra-toggle").click();
assert.equal(await page.locator("#eg-extra .eg-extra-choices button").count(),3,"Basque quest question missing");
await page.locator("#eg-extra .eg-extra-choices button").nth(1).click();
assert((await page.locator("#eg-extra").textContent()).includes("02 · EKINTZA"),"Quest level 2 not unlocked");
assert.equal(await page.locator("#egStars").textContent(),"1/108","Quest progress not tracked");
await page.locator("#eg-extra-toggle").click();
await page.locator("#frame").waitFor({timeout:5000});
const source=await page.locator("#frame").getAttribute("src");
assert(source.includes("/klasiko/?joko=pilota"),"Sports must load actual preserved game");
await page.waitForFunction(()=>{
  const legacy=document.querySelector("#frame")?.contentDocument;
  const inner=legacy?.querySelector("#gameFrame");
  return !!inner && (inner.getAttribute("srcdoc")||"").length>10000;
},{timeout:12000});
const pilotaBytes=await page.locator("#frame").evaluate(f=>f.contentDocument?.querySelector("#gameFrame")?.getAttribute("srcdoc")?.length||0);
assert(pilotaBytes>10000,"Classic pilota code did not load");
await page.locator("#close").click();
await page.locator(".feature-tile.basoa").click();
await page.waitForFunction(()=>{
  const legacy=document.querySelector("#frame")?.contentDocument;
  const inner=legacy?.querySelector("#gameFrame");
  return !!inner && (inner.getAttribute("srcdoc")||"").length>10000;
},{timeout:12000});
await page.locator("#close").click();
await page.locator("#mundu").scrollIntoViewIfNeeded();
await page.locator(".gamecard .openrow button").first().click();
assert((await page.locator("#frame").getAttribute("src")).includes("/mundu-jolastuak/games/"),"31 originals must launch local translated game");
await page.locator("#close").click();
assert.equal(await page.locator(".feature-tile").count(),5);
if(errors.some(x=>/SyntaxError|ReferenceError|TypeError/i.test(x)))throw new Error("Portal browser errors: "+errors.join("; "));
console.log(JSON.stringify({cards:31,originalGames:5,search:true,favorites:true,language:true,launch:true,basqueExtraQuests:108,questProgress:true,textOnlyLogo:true,errors},null,2));
await browser.close();
